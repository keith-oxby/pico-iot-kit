"""Stages what gets frozen into the .uf2 (checklist item 9).

Copies every .py file under firmware/ into a staging directory, puts
firmware/main.py at its root (MicroPython runs a frozen main.py itself) and
generates the setup page module from the HTML template. build/manifest.py
then freezes the whole staging directory, so a new module can't be left
out of the image. Runs on the host (tests) and in the build container.

    python3 build/stage.py STAGE_DIR [REPO_DIR]
"""

import os
import shutil
import sys

PAGE_SOURCE = os.path.join("firmware", "provisioning", "templates", "setup.html")
PAGE_MODULE = os.path.join("firmware", "provisioning", "_setup_page.py")
MAIN = os.path.join("firmware", "main.py")

_HEADER = '''"""Generated by build/stage.py from templates/setup.html. Do not edit."""

PAGE = '''


def page_module_source(html):
    """Python source for a module whose PAGE is exactly `html`."""
    return _HEADER + repr(html) + "\n"


def stage(repo_dir, stage_dir):
    """Fill `stage_dir` (created, must not already hold files); return the
    staged paths, relative to it."""
    if os.path.exists(stage_dir) and os.listdir(stage_dir):
        raise ValueError("%s is not empty" % stage_dir)
    firmware = os.path.join(repo_dir, "firmware")
    staged = []
    for root, dirs, files in os.walk(firmware):
        dirs[:] = sorted(d for d in dirs if d != "__pycache__")
        for name in sorted(files):
            if not name.endswith(".py"):
                continue
            source = os.path.join(root, name)
            relative = os.path.relpath(source, repo_dir)
            if relative == MAIN:
                target_relative = "main.py"
            else:
                target_relative = relative
            target = os.path.join(stage_dir, target_relative)
            os.makedirs(os.path.dirname(target), exist_ok=True)
            shutil.copyfile(source, target)
            staged.append(target_relative)

    with open(os.path.join(repo_dir, PAGE_SOURCE), encoding="utf-8", newline="") as f:
        html = f.read()
    module = os.path.join(stage_dir, PAGE_MODULE)
    with open(module, "w", encoding="utf-8", newline="") as f:
        f.write(page_module_source(html))
    staged.append(PAGE_MODULE)
    return staged


if __name__ == "__main__":
    if not 2 <= len(sys.argv) <= 3:
        sys.exit(__doc__)
    repo = sys.argv[2] if len(sys.argv) == 3 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for path in stage(repo, sys.argv[1]):
        print(path)
